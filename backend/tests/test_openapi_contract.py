"""The API contract is a reviewed file, docs/openapi.json (direction item G).

Production-readiness direction, 2026-10-07, item G: the OpenAPI document sits
beside the brief and the architecture as a reviewable file, and CI fails when
the code drifts from it. A contract change then shows up in review as a diff to
that file, never silently. To accept a deliberate change, regenerate it:

    uv run python scripts/export_openapi.py

Codex, 2026-10-11 (P2 on PR #20): the document was generated by, and compared
against, the app as configured. A shell APP_NAME changed its title, so the
exporter wrote a different contract and the drift test failed with no code
change. The contract is now built in a fresh process whose settings all take
their defaults from the code. Both the exporter and this test use that one
path.
"""

import importlib.util
import json
from pathlib import Path
from types import ModuleType

import pytest

from backend.app.core.config import AppSettings

REPO = Path(__file__).resolve().parents[2]
CONTRACT = REPO / "docs" / "openapi.json"
REGENERATE = "regenerate it with: uv run python scripts/export_openapi.py"


def _exporter() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "export_openapi", REPO / "scripts" / "export_openapi.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _committed() -> dict[str, object]:
    assert CONTRACT.exists(), f"docs/openapi.json is missing; {REGENERATE}"
    return json.loads(CONTRACT.read_text())


def test_the_committed_contract_matches_the_code() -> None:
    assert _exporter().canonical_document() == _committed(), (
        f"the API contract changed; review it, then {REGENERATE}"
    )


def test_the_contract_documents_every_route() -> None:
    """Not vacuous: the committed file is the real, complete contract."""
    assert set(_committed()["paths"]) == {
        "/",
        "/health",
        "/generate-meal-plan",
        "/meal-plans/{user_id}",
        "/calorie-expenditure/predict",
        "/meal-feedback",
        "/meal-feedback/{user_id}",
        "/saved-meals/{user_id}",
    }


def test_a_custom_shell_environment_does_not_change_the_contract(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Codex's reproduction: APP_NAME (and any other setting) in the shell."""
    for name, value in {
        "APP_NAME": "review-custom-title",
        "APP_ENV": "production",
        "HOSTED_MODE": "true",
        "ALLOWED_ORIGINS": "https://example.invalid",
        "SKIP_DOTENV": "0",
    }.items():
        monkeypatch.setenv(name, value)

    document = _exporter().canonical_document()

    assert document["info"]["title"] == AppSettings.model_fields["app_name"].default
    assert document == _committed()


def test_the_contract_is_built_with_no_setting_and_no_dotenv() -> None:
    """Only what the interpreter needs; SKIP_DOTENV is forced, whatever the caller set.

    backend/.env is the developer's own file, so this checks the generation
    environment rather than writing a dotenv file for the test.
    """
    exporter = _exporter()
    caller = {
        "PATH": "/usr/bin",
        "APP_NAME": "custom",
        "API_KEYS": '[{"client_id": "x"}]',
        "SKIP_DOTENV": "0",
        "VIRTUAL_ENV": "/elsewhere",
    }

    assert exporter.contract_environment(caller) == {
        "PATH": "/usr/bin",
        "PYTHONPATH": str(REPO),
        "SKIP_DOTENV": "1",
    }
